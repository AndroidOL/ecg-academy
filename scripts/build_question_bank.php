<?php
declare(strict_types=1);

require dirname(__DIR__) . '/app/bootstrap.php';

use App\Content;

$variantsPerDiagnosis = 25;
$variantsPerCombo = 25;
$entries = [];
$questionForms = [
    '该心电图最可能的诊断是？',
    '请判读该心电图，选择最可能的诊断。',
    '该心电图最符合哪项诊断？',
];

foreach (Content::all() as $diagnosis) {
    if (($diagnosis['quizEligible'] ?? true) === false) continue;
    $level = max(1, min(3, (int) ($diagnosis['difficulty'] ?? 1)));
    for ($variant = 0; $variant < $variantsPerDiagnosis; $variant++) {
        $id = sprintf('q-%s-%02d', $diagnosis['id'], $variant + 1);
        $baseRate = (int) ($diagnosis['ecg']['rate'] ?? 0);
        $step = $baseRate <= 60 ? 1 : ($baseRate <= 100 ? 2 : ($baseRate <= 160 ? 4 : 6));
        $rate = $baseRate > 0 ? max(20, $baseRate + (($variant % 5) - 2) * $step) : null;
        $entries[] = [
            'id' => $id,
            'primary' => $diagnosis['id'],
            'secondary' => null,
            'combo' => null,
            'level' => $level,
            'chapter' => $diagnosis['chapter'],
            'seed' => max(1, (int) sprintf('%u', crc32($id)) % 2147483647),
            'variant' => $variant,
            'rate' => $rate,
            'question' => $questionForms[$variant % count($questionForms)],
            'stem' => '',
        ];
    }
}

$combos = require BASE_PATH . '/data/combos.php';
foreach ($combos as $combo) {
    $primary = Content::find($combo['primary']);
    $secondary = Content::find($combo['secondary']);
    if (!$primary || !$secondary) continue;
    for ($variant = 0; $variant < $variantsPerCombo; $variant++) {
        $id = sprintf('q-combo-%s-%02d', $combo['id'], $variant + 1);
        $entries[] = [
            'id' => $id,
            'primary' => $primary['id'],
            'secondary' => $secondary['id'],
            'combo' => $combo['id'],
            'level' => 3,
            'chapter' => $primary['chapter'],
            'seed' => max(1, (int) sprintf('%u', crc32($id)) % 2147483647),
            'variant' => $variant,
            'rate' => null,
            'question' => '该心电图包含哪些诊断？（多选）',
            'stem' => (string) ($combo['stem'] ?? ''),
        ];
    }
}

$output = "<?php\n// Generated by scripts/build_question_bank.php — " . count($entries) . " deterministic cases.\nreturn " . var_export($entries, true) . ";\n";
file_put_contents(BASE_PATH . '/data/question_bank.php', $output);
echo 'Question bank: ' . count($entries) . " cases\n";
